class QuizQuest {
    constructor() {
        this.questions = DIWALI_QUIZ_QUESTIONS;
        this.currentIndex = 0;
        this.score = 0;
        this.answered = false;

        this.init();
    }

    init() {
        this.renderQuestion();
        this.bindEvents();
    }

    bindEvents() {
        const nextBtn = document.getElementById('quiz-next-btn');
        if (nextBtn) {
            nextBtn.addEventListener('click', () => this.handleNext());
        }

        const restartBtn = document.getElementById('quiz-restart-btn');
        if (restartBtn) {
            restartBtn.addEventListener('click', () => this.restart());
        }

        const generateCertBtn = document.getElementById('generate-certificate-btn');
        if (generateCertBtn) {
            generateCertBtn.addEventListener('click', () => this.generateCertificate());
        }
    }

    renderQuestion() {
        const q = this.questions[this.currentIndex];
        this.answered = false;

        const progressEl = document.getElementById('quiz-progress-text');
        const progressBar = document.getElementById('quiz-progress-fill');
        const questionEl = document.getElementById('quiz-question-title');
        const optionsContainer = document.getElementById('quiz-options-grid');
        const feedbackEl = document.getElementById('quiz-feedback-box');
        const nextBtn = document.getElementById('quiz-next-btn');

        if (progressEl) progressEl.innerText = `Question ${this.currentIndex + 1} of ${this.questions.length}`;
        if (progressBar) progressBar.style.width = `${((this.currentIndex) / this.questions.length) * 100}%`;
        if (questionEl) questionEl.innerText = q.question;
        if (feedbackEl) feedbackEl.className = 'quiz-feedback-box hidden';
        if (nextBtn) nextBtn.disabled = true;

        if (optionsContainer) {
            optionsContainer.innerHTML = '';
            q.options.forEach((opt, idx) => {
                const btn = document.createElement('button');
                btn.className = 'quiz-option-btn';
                btn.type = 'button';
                btn.innerHTML = `<span class="opt-prefix">${String.fromCharCode(65 + idx)}</span> <span class="opt-text">${opt}</span>`;

                btn.addEventListener('click', () => this.selectOption(idx, btn));
                optionsContainer.appendChild(btn);
            });
        }
    }

    selectOption(index, button) {
        if (this.answered) return;
        this.answered = true;
        window.diwaliAudio.ensureContext();

        const q = this.questions[this.currentIndex];
        const options = document.querySelectorAll('.quiz-option-btn');
        const feedbackEl = document.getElementById('quiz-feedback-box');
        const nextBtn = document.getElementById('quiz-next-btn');

        options.forEach(b => b.disabled = true);

        if (index === q.correct) {
            this.score++;
            button.classList.add('correct');
            window.diwaliAudio.playTempleChime(1046.5, 0.4);

            if (feedbackEl) {
                feedbackEl.className = 'quiz-feedback-box correct-feedback';
                feedbackEl.innerHTML = `<strong>🎉 Brilliant! That is Correct!</strong><p>${q.explanation}</p>`;
            }
        } else {
            button.classList.add('incorrect');
            if (options[q.correct]) options[q.correct].classList.add('correct');
            window.diwaliAudio.playClick();

            if (feedbackEl) {
                feedbackEl.className = 'quiz-feedback-box incorrect-feedback';
                feedbackEl.innerHTML = `<strong>💡 Good Effort! The correct answer was ${String.fromCharCode(65 + q.correct)}.</strong><p>${q.explanation}</p>`;
            }
        }

        if (nextBtn) nextBtn.disabled = false;
    }

    handleNext() {
        this.currentIndex++;
        if (this.currentIndex < this.questions.length) {
            this.renderQuestion();
        } else {
            this.showResults();
        }
    }

    showResults() {
        const questCard = document.getElementById('quiz-question-card');
        const resultsCard = document.getElementById('quiz-results-card');
        const scoreVal = document.getElementById('quiz-final-score');
        const totalVal = document.getElementById('quiz-total-score');
        const msgEl = document.getElementById('quiz-result-message');

        if (questCard) questCard.classList.add('hidden');
        if (resultsCard) resultsCard.classList.remove('hidden');

        if (scoreVal) scoreVal.innerText = this.score;
        if (totalVal) totalVal.innerText = this.questions.length;

        const percent = (this.score / this.questions.length) * 100;
        let msg = '';
        if (percent === 100) {
            msg = '🌟 Exceptional! You are an Official Grandmaster of Diwali Traditions & Science!';
        } else if (percent >= 70) {
            msg = '🪔 Outstanding work! You have deep mastery over the festive history and pyrotechnic chemistry!';
        } else {
            msg = '✨ Wonderful attempt! You have learned fascinating scientific and cultural secrets of Diwali!';
        }
        if (msgEl) msgEl.innerText = msg;

        window.diwaliAudio.playSuccessFanfare();
        this.launchConfetti();
    }

    restart() {
        this.currentIndex = 0;
        this.score = 0;
        this.answered = false;

        const questCard = document.getElementById('quiz-question-card');
        const resultsCard = document.getElementById('quiz-results-card');
        if (questCard) questCard.classList.remove('hidden');
        if (resultsCard) resultsCard.classList.add('hidden');

        this.renderQuestion();
    }

    launchConfetti() {
        const canvas = document.getElementById('confetti-canvas');
        if (!canvas) return;
        const ctx = canvas.getContext('2d');
        const parent = canvas.parentElement;
        canvas.width = parent.clientWidth;
        canvas.height = 360;

        const confettis = [];
        const colors = ['#ffd700', '#ff0055', '#00ff88', '#00d4ff', '#ffbe33', '#e0aaff'];

        for (let i = 0; i < 80; i++) {
            confettis.push({
                x: Math.random() * canvas.width,
                y: -10 - Math.random() * 50,
                size: 6 + Math.random() * 8,
                color: colors[Math.floor(Math.random() * colors.length)],
                vx: (Math.random() - 0.5) * 4,
                vy: 2 + Math.random() * 4,
                rot: Math.random() * Math.PI,
                vrot: (Math.random() - 0.5) * 0.2
            });
        }

        let frames = 0;
        const animate = () => {
            frames++;
            ctx.clearRect(0, 0, canvas.width, canvas.height);
            confettis.forEach(c => {
                c.x += c.vx;
                c.y += c.vy;
                c.rot += c.vrot;

                ctx.save();
                ctx.translate(c.x, c.y);
                ctx.rotate(c.rot);
                ctx.fillStyle = c.color;
                ctx.fillRect(-c.size / 2, -c.size / 2, c.size, c.size * 0.6);
                ctx.restore();
            });

            if (frames < 180) requestAnimationFrame(animate);
            else ctx.clearRect(0, 0, canvas.width, canvas.height);
        };
        requestAnimationFrame(animate);
    }

    generateCertificate() {
        const nameInput = document.getElementById('cert-student-name');
        const studentName = nameInput && nameInput.value.trim() ? nameInput.value.trim() : 'Brilliant Diwali Explorer';

        const canvas = document.getElementById('certificate-canvas');
        if (!canvas) return;
        const ctx = canvas.getContext('2d');
        canvas.width = 1000;
        canvas.height = 680;

        // Background parchment & royal border
        const bgGrad = ctx.createLinearGradient(0, 0, 1000, 680);
        bgGrad.addColorStop(0, '#100a20');
        bgGrad.addColorStop(0.5, '#1e1238');
        bgGrad.addColorStop(1, '#0c0717');
        ctx.fillStyle = bgGrad;
        ctx.fillRect(0, 0, 1000, 680);

        // Gold frame
        ctx.strokeStyle = '#ffd700';
        ctx.lineWidth = 6;
        ctx.strokeRect(30, 30, 940, 620);

        ctx.strokeStyle = 'rgba(255, 215, 0, 0.4)';
        ctx.lineWidth = 2;
        ctx.strokeRect(42, 42, 916, 596);

        // Header Title
        ctx.save();
        ctx.textAlign = 'center';
        ctx.fillStyle = '#ffbe33';
        ctx.font = '20px "Cinzel Decorative", Cinzel, serif';
        ctx.fillText('✨ JETLEARN AI INVENTORS & SCIENCE LAB ✨', 500, 95);

        ctx.font = 'bold 36px "Cinzel Decorative", Cinzel, serif';
        ctx.fillStyle = '#ffffff';
        ctx.shadowColor = '#ffd700';
        ctx.shadowBlur = 12;
        ctx.fillText('CERTIFICATE OF SCIENTIFIC EXCELLENCE', 500, 155);

        ctx.font = '16px Poppins, sans-serif';
        ctx.fillStyle = '#cccccc';
        ctx.shadowBlur = 0;
        ctx.fillText('THIS PRESTIGIOUS ACCREDITATION IS PROUDLY CONFERRED UPON', 500, 210);

        // Student Name
        ctx.font = 'bold 44px "Cinzel Decorative", Cinzel, serif';
        ctx.fillStyle = '#ffd700';
        ctx.shadowColor = '#ffaa00';
        ctx.shadowBlur = 16;
        ctx.fillText(studentName, 500, 275);
        ctx.shadowBlur = 0;

        // Certification text
        ctx.font = '17px Poppins, sans-serif';
        ctx.fillStyle = '#f0f0f0';
        ctx.fillText(
            `For outstanding mastery in the Festive Traditions, Spectroscopic Chemistry of Fireworks,`,
            500,
            335
        );
        ctx.fillText(
            `and Capillary Fluid Dynamics of Diyas during the Diwali Science Exploration Program.`,
            500,
            365
        );

        // Score Badge
        ctx.font = 'bold 20px Poppins, sans-serif';
        ctx.fillStyle = '#06d6a0';
        ctx.fillText(`🏆 Score Achieved: ${this.score} / ${this.questions.length} (${Math.round((this.score / this.questions.length) * 100)}%)`, 500, 420);

        // Date & Seal
        const dateStr = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' });
        ctx.font = '15px Poppins, sans-serif';
        ctx.fillStyle = '#aaaaaa';
        ctx.fillText(`Date: ${dateStr}`, 260, 560);
        ctx.fillText('Authorized Diwali STEM Lab', 740, 560);

        // Golden Seal in center
        ctx.beginPath();
        ctx.arc(500, 520, 45, 0, Math.PI * 2);
        ctx.fillStyle = '#ffd700';
        ctx.fill();
        ctx.strokeStyle = '#b8860b';
        ctx.lineWidth = 3;
        ctx.stroke();

        ctx.font = 'bold 13px Poppins, sans-serif';
        ctx.fillStyle = '#110a1d';
        ctx.fillText('DIWALI', 500, 514);
        ctx.fillText('MASTER', 500, 532);

        ctx.restore();

        // Download trigger
        window.diwaliAudio.playSuccessFanfare();
        const link = document.createElement('a');
        link.download = `Diwali_Master_Certificate_${studentName.replace(/[^a-zA-Z0-9]/g, '_')}.png`;
        link.href = canvas.toDataURL('image/png');
        link.click();
    }
}

window.QuizQuest = QuizQuest;
